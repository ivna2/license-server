-- Пользователи, роли и сессии (перенесены из прошлого проекта)
CREATE TABLE users (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(254) NOT NULL UNIQUE,
    password VARCHAR(255) NOT NULL,
    enabled  BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE role (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(50) NOT NULL UNIQUE
);

CREATE TABLE user_roles (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES role (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE user_sessions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    refresh_token TEXT         NOT NULL UNIQUE,
    user_id       VARCHAR(254) NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    created_at    TIMESTAMP(6) NOT NULL,
    expires_at    TIMESTAMP(6) NOT NULL
);
CREATE INDEX idx_user_sessions_user_status ON user_sessions (user_id, status);

-- Модуль лицензий
CREATE TABLE product (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL UNIQUE,
    is_blocked BOOLEAN      NOT NULL DEFAULT FALSE
);

CREATE TABLE license_type (
    id                       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                     VARCHAR(100) NOT NULL UNIQUE,
    default_duration_in_days INTEGER      NOT NULL CHECK (default_duration_in_days > 0),
    description              TEXT
);

CREATE TABLE license (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                  VARCHAR(64) NOT NULL UNIQUE,
    user_id               BIGINT      REFERENCES users (id),
    owner_id              BIGINT      NOT NULL REFERENCES users (id),
    product_id            BIGINT      NOT NULL REFERENCES product (id),
    type_id               BIGINT      NOT NULL REFERENCES license_type (id),
    first_activation_date TIMESTAMP(6) WITH TIME ZONE,
    ending_date           TIMESTAMP(6) WITH TIME ZONE,
    blocked               BOOLEAN     NOT NULL DEFAULT FALSE,
    device_count          INTEGER     NOT NULL CHECK (device_count > 0),
    description           TEXT
);

CREATE TABLE device (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL,
    mac_address VARCHAR(17)  NOT NULL UNIQUE,
    user_id     BIGINT       NOT NULL REFERENCES users (id)
);

CREATE TABLE device_license (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id      BIGINT NOT NULL REFERENCES license (id),
    device_id       BIGINT NOT NULL REFERENCES device (id),
    activation_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UNIQUE (license_id, device_id)
);

CREATE TABLE license_history (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    license_id  BIGINT      NOT NULL REFERENCES license (id),
    user_id     BIGINT      NOT NULL REFERENCES users (id),
    status      VARCHAR(20) NOT NULL,
    change_date TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    description TEXT
);
CREATE INDEX idx_license_history_license ON license_history (license_id);
